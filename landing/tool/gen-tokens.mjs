#!/usr/bin/env node
// Generates the site's CSS design tokens from design/tokens.json, the same source as the app's
// mobile/lib/theme/tokens.g.dart (tools/gen_flutter_tokens.py).
//
//   npm run tokens          writes src/styles/tokens.css
//   npm run check-tokens    exits 1 if src/styles/tokens.css is stale
//
// --out <file> writes (or checks) another file instead, relative to the current folder: the admin (admin/) uses
// the same tokens through its own npm run tokens and check-tokens.
//
// The output is committed, so building the site needs only landing/. Node standard library only.
//
// What is generated, as CSS custom properties on :root:
//   * colours: light values, then dark values under prefers-color-scheme: dark; aliases such as
//     "{primary}" become var(--primary), so they follow the theme;
//   * shadows (light and dark), spacing, radii, sizes;
//   * font families and the type scale: --<style>-size, -line, -weight and -tracking.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, '..', '..');
const SOURCE = join(ROOT, 'design', 'tokens.json');
const out = process.argv.indexOf('--out');
if (out !== -1 && !process.argv[out + 1]) throw new Error('--out needs a file');
const TARGET = out === -1 ? join(here, '..', 'src', 'styles', 'tokens.css') : resolve(process.argv[out + 1]);
// The folder whose npm run tokens regenerates the file ("landing", "admin"), and the file as the messages show it.
const OWNER = relative(ROOT, TARGET).split(sep)[0];
const SHOWN = relative(process.cwd(), TARGET);

const ALIAS = /^\{([a-z0-9-]+)\}$/;
const HEX = /^#([0-9a-fA-F]{6}|[0-9a-fA-F]{8})$/;

const tokens = JSON.parse(readFileSync(SOURCE, 'utf8'));
const themes = tokens.color.themes.map((theme) => theme.id);
if (themes.join() !== 'light,dark') {
  throw new Error(`Expected the themes light and dark, got ${themes.join(', ')}`);
}

/** One `--name: value;` line, with the token's usage note above it. */
function line(name, value, usage) {
  const note = usage ? `  /* ${usage.replaceAll('*/', '* /')} */\n` : '';
  return `${note}  --${name}: ${value};`;
}

function color(value, name) {
  if (!HEX.test(value)) throw new Error(`Colour ${name}: "${value}" is not #rrggbb or #rrggbbaa`);
  return value.toLowerCase();
}

const light = [];
const dark = [];

light.push('  /* Colours */');
dark.push('  /* Colours */');
for (const token of tokens.color.tokens) {
  const { name, value, usage } = token;
  if (typeof value === 'string') {
    const alias = ALIAS.exec(value);
    if (!alias) throw new Error(`Colour ${name}: "${value}" is neither an alias nor per-theme values`);
    light.push(line(name, `var(--${alias[1]})`, usage));
    continue;
  }
  light.push(line(name, color(value.light, name), usage));
  dark.push(`  --${name}: ${color(value.dark, name)};`);
}

light.push('', '  /* Shadows */');
dark.push('', '  /* Shadows */');
for (const { name, value, usage } of tokens.shadow.tokens) {
  light.push(line(name, value.light, usage));
  dark.push(`  --${name}: ${value.dark};`);
}

for (const [group, title] of [
  ['spacing', 'Spacing'],
  ['radius', 'Radii'],
  ['size', 'Sizes'],
]) {
  light.push('', `  /* ${title}${tokens[group].note ? `: ${tokens[group].note}` : ''} */`);
  for (const { name, value, usage } of tokens[group].tokens) light.push(line(name, value, usage));
}

light.push('', '  /* Font families */');
for (const [name, value] of Object.entries(tokens.type.families)) light.push(`  --font-${name}: ${value};`);

light.push('', '  /* Type scale */');
for (const group of tokens.type.groups) {
  for (const style of group.styles) {
    light.push(`  /* ${style.name}: ${style.usage} */`);
    light.push(`  --${style.name}-family: var(--font-${group.family});`);
    light.push(`  --${style.name}-size: ${style.fontSize};`);
    light.push(`  --${style.name}-line: ${style.lineHeight};`);
    light.push(`  --${style.name}-weight: ${style.fontWeight};`);
    light.push(`  --${style.name}-tracking: ${style.letterSpacing ?? 'normal'};`);
  }
}

const css = `/* GENERATED by landing/tool/gen-tokens.mjs from design/tokens.json — do not edit.
   Design system: ${tokens.name}, tokens version ${tokens.version}. Regenerate: npm run tokens (in ${OWNER}/). */

:root {
${light.join('\n')}
}

@media (prefers-color-scheme: dark) {
  :root {
${dark.map((text) => (text ? `  ${text}` : text)).join('\n')}
  }
}
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(TARGET, 'utf8');
  } catch {
    // Missing counts as stale.
  }
  if (current !== css) {
    console.error(`${SHOWN} is stale: run npm run tokens`);
    process.exit(1);
  }
  console.log(`${SHOWN} is up to date`);
} else {
  writeFileSync(TARGET, css);
  console.log(`Wrote ${SHOWN}`);
}
