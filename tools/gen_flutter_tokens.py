#!/usr/bin/env python3
"""Generate the Flutter design tokens from design/tokens.json.

    python3 tools/gen_flutter_tokens.py           # writes mobile/lib/theme/tokens.g.dart
    python3 tools/gen_flutter_tokens.py --check   # exits 1 if the Dart file is stale (CI)

Standard library only. The output is formatted the way `dart format` would
format it, so the generated file never shows up as a formatting diff.

What is generated:
  * CbTokenColors   - one const field per colour token, `light` and `dark`
                      instances; aliases like "{primary}" are resolved here;
  * CbTokenShadows  - CSS box-shadow tokens parsed into BoxShadow lists;
  * CbSpace, CbRadius, CbSize - numeric scales as doubles;
  * CbFontFamily, CbTypeSpec, CbTypeScale - the type scale, independent of
    the font loader (lib/theme applies Google Fonts on top).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "design" / "tokens.json"
TARGET = ROOT / "mobile" / "lib" / "theme" / "tokens.g.dart"

HEADER = "// GENERATED by tools/gen_flutter_tokens.py from design/tokens.json — do not edit."
MAX_COMMENT_WIDTH = 80

DART_RESERVED = {
    "abstract", "as", "assert", "async", "await", "base", "break", "case", "catch",
    "class", "const", "continue", "covariant", "default", "deferred", "do",
    "dynamic", "else", "enum", "export", "extends", "extension", "external",
    "factory", "false", "final", "finally", "for", "function", "get", "hide",
    "if", "implements", "import", "in", "interface", "is", "late", "library",
    "mixin", "new", "null", "of", "on", "operator", "part", "required", "rethrow",
    "return", "sealed", "set", "show", "static", "super", "switch", "sync",
    "this", "throw", "true", "try", "type", "typedef", "var", "void", "when",
    "while", "with", "yield",
}

ALIAS_RE = re.compile(r"^\{([a-z0-9-]+)\}$")
HEX_RE = re.compile(r"^#([0-9a-fA-F]{6}|[0-9a-fA-F]{8})$")
PX_RE = re.compile(r"^(-?\d+(?:\.\d+)?)px$")
EM_RE = re.compile(r"^(-?\d*\.?\d+)em$")
LENGTH_RE = re.compile(r"^(-?\d+(?:\.\d+)?)(px)?$")


class TokenError(Exception):
    """The tokens file does not match the expected shape."""


# --------------------------------------------------------------------------- #
# Small helpers
# --------------------------------------------------------------------------- #


def camel(name: str) -> str:
    """`ink-muted` -> `inkMuted`, `on-primary` -> `onPrimary`."""
    parts = [p for p in name.split("-") if p]
    if not parts:
        raise TokenError(f"empty token name: {name!r}")
    ident = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    if not re.match(r"^[a-z][A-Za-z0-9]*$", ident):
        raise TokenError(f"token {name!r} does not map to a Dart identifier ({ident!r})")
    if ident in DART_RESERVED:
        raise TokenError(f"token {name!r} maps to the reserved Dart word {ident!r}")
    return ident


def strip_prefix(name: str, prefix: str) -> str:
    if not name.startswith(prefix):
        raise TokenError(f"token {name!r} should start with {prefix!r}")
    return name[len(prefix):]


def px(value: str, where: str) -> float:
    match = PX_RE.match(str(value).strip())
    if not match:
        raise TokenError(f"{where}: expected a px value like '16px', got {value!r}")
    return float(match.group(1))


def em(value: str, where: str) -> float:
    match = EM_RE.match(str(value).strip())
    if not match:
        raise TokenError(f"{where}: expected an em value like '0.02em', got {value!r}")
    return float(match.group(1))


def num(value: float) -> str:
    """A Dart numeric literal for a double-typed slot: 16.0 -> `16`, 0.28 -> `0.28`."""
    value = round(value, 4)
    if value == int(value):
        return str(int(value))
    return repr(value)


def argb(hex_value: str, where: str) -> str:
    """`#rrggbb` or `#rrggbbaa` (CSS order) -> `0xAARRGGBB` (Flutter order)."""
    match = HEX_RE.match(str(hex_value).strip())
    if not match:
        raise TokenError(f"{where}: expected #rrggbb or #rrggbbaa, got {hex_value!r}")
    digits = match.group(1).upper()
    rgb, alpha = digits[:6], digits[6:] or "FF"
    return f"0x{alpha}{rgb}"


def doc(text: str | None, indent: str) -> list[str]:
    """A `///` doc comment, wrapped to the comment width."""
    if not text:
        return []
    width = max(40, MAX_COMMENT_WIDTH - len(indent) - 4)
    lines: list[str] = []
    for paragraph in str(text).strip().split("\n"):
        wrapped = textwrap.wrap(paragraph.strip(), width=width, break_long_words=False,
                                break_on_hyphens=False) or [""]
        lines.extend(f"{indent}/// {line}".rstrip() for line in wrapped)
    return lines


def dart_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def require(obj: dict, key: str, where: str):
    if key not in obj:
        raise TokenError(f"{where}: missing {key!r}")
    return obj[key]


# --------------------------------------------------------------------------- #
# Colours
# --------------------------------------------------------------------------- #


def resolve_colors(color: dict) -> tuple[list[str], list[dict]]:
    """Returns theme ids and tokens with every value resolved to a hex per theme."""
    themes = [require(t, "id", "color.themes[]") for t in require(color, "themes", "color")]
    if not themes:
        raise TokenError("color.themes is empty")
    tokens = require(color, "tokens", "color")
    raw = {}
    for token in tokens:
        name = require(token, "name", "color.tokens[]")
        if name in raw:
            raise TokenError(f"duplicate colour token {name!r}")
        raw[name] = token

    def resolve(name: str, theme: str, chain: tuple[str, ...]) -> str:
        if name not in raw:
            raise TokenError(f"colour alias {' -> '.join(chain)} -> {name!r}: unknown token")
        if name in chain:
            raise TokenError(f"colour alias cycle: {' -> '.join(chain + (name,))}")
        value = require(raw[name], "value", f"color.tokens[{name}]")
        if isinstance(value, dict):
            if theme not in value:
                raise TokenError(f"colour token {name!r} has no value for theme {theme!r}")
            return value[theme]
        alias = ALIAS_RE.match(str(value).strip())
        if not alias:
            raise TokenError(f"colour token {name!r}: expected {{light, dark}} or '{{alias}}', got {value!r}")
        return resolve(alias.group(1), theme, chain + (name,))

    resolved = []
    for name, token in raw.items():
        value = token["value"]
        alias = ALIAS_RE.match(value.strip()) if isinstance(value, str) else None
        per_theme = {t: argb(resolve(name, t, ()), f"color {name}/{t}") for t in themes}
        resolved.append({
            "name": name,
            "field": camel(name),
            "usage": token.get("usage"),
            "alias": alias.group(1) if alias else None,
            "values": per_theme,
        })
    fields = [t["field"] for t in resolved]
    if len(set(fields)) != len(fields):
        raise TokenError("two colour tokens map to the same Dart field name")
    return themes, resolved


def gen_colors(themes: list[str], colors: list[dict]) -> list[str]:
    out = [
        "/// Colour tokens (`color.tokens`) for one theme.",
        "///",
        "/// Aliases such as `success-soft` = `{primary-soft}` are resolved by the",
        "/// generator, so every field is a concrete colour. Wrapped by the `CbColors` theme",
        "/// extension in collarbell_theme.dart; read them with `context.cb`.",
        "class CbTokenColors {",
        "  const CbTokenColors({",
    ]
    out += [f"    required this.{c['field']}," for c in colors]
    out.append("  });")
    for c in colors:
        out.append("")
        usage = c["usage"] or ""
        if c["alias"]:
            usage = f"Alias of `{c['alias']}`. {usage}".strip()
        out += doc(f"`{c['name']}`: {usage}" if usage else f"`{c['name']}`.", "  ")
        out.append(f"  final Color {c['field']};")
    out += [
        "",
        "  /// Interpolates every token, e.g. while the theme animates light <-> dark.",
        "  static CbTokenColors lerp(CbTokenColors a, CbTokenColors b, double t) {",
        "    return CbTokenColors(",
    ]
    out += [f"      {c['field']}: Color.lerp(a.{c['field']}, b.{c['field']}, t)!," for c in colors]
    out += ["    );", "  }"]
    for theme in themes:
        out += ["", f"  /// Theme `{theme}`.", f"  static const {camel(theme)} = CbTokenColors("]
        out += [f"    {c['field']}: Color({c['values'][theme]})," for c in colors]
        out.append("  );")
    out.append("}")
    return out


# --------------------------------------------------------------------------- #
# Shadows
# --------------------------------------------------------------------------- #


def split_commas(css: str) -> list[str]:
    parts, depth, current = [], 0, ""
    for ch in css:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(current.strip())
            current = ""
        else:
            current += ch
    if current.strip():
        parts.append(current.strip())
    return parts


def parse_box_shadows(css: str, where: str) -> list[dict]:
    shadows = []
    for layer in split_commas(css):
        words = layer.split()
        if "inset" in words:
            raise TokenError(f"{where}: inset shadows are not supported in Flutter ({layer!r})")
        colors = [w for w in words if w.startswith("#")]
        lengths = [w for w in words if not w.startswith("#")]
        if len(colors) != 1 or not 2 <= len(lengths) <= 4:
            raise TokenError(f"{where}: cannot parse box-shadow layer {layer!r}")
        values = []
        for length in lengths:
            match = LENGTH_RE.match(length)
            if not match:
                raise TokenError(f"{where}: bad length {length!r} in {layer!r}")
            values.append(float(match.group(1)))
        values += [0.0] * (4 - len(values))
        x, y, blur, spread = values
        shadows.append({"color": argb(colors[0], where), "x": x, "y": y, "blur": blur, "spread": spread})
    return shadows


def box_shadow(s: dict) -> str:
    args = [f"color: Color({s['color']})"]
    if s["x"] or s["y"]:
        args.append(f"offset: Offset({num(s['x'])}, {num(s['y'])})")
    if s["blur"]:
        args.append(f"blurRadius: {num(s['blur'])}")
    if s["spread"]:
        args.append(f"spreadRadius: {num(s['spread'])}")
    return f"BoxShadow({', '.join(args)})"


def gen_shadows(themes: list[str], shadow: dict) -> list[str]:
    tokens = []
    for token in require(shadow, "tokens", "shadow"):
        name = require(token, "name", "shadow.tokens[]")
        field = camel(name[len("shadow-"):] if name.startswith("shadow-") else name)
        value = require(token, "value", f"shadow {name}")
        if not isinstance(value, dict):
            raise TokenError(f"shadow {name!r}: expected a value per theme")
        tokens.append({
            "name": name,
            "field": field,
            "usage": token.get("usage"),
            "values": {t: parse_box_shadows(require(value, t, f"shadow {name}"), f"shadow {name}/{t}")
                       for t in themes},
        })
    out = [
        "/// Shadow tokens (`shadow.tokens`) for one theme, parsed from CSS box-shadow.",
        "class CbTokenShadows {",
        "  const CbTokenShadows({",
    ]
    out += [f"    required this.{t['field']}," for t in tokens]
    out.append("  });")
    for t in tokens:
        out.append("")
        out += doc(f"`{t['name']}`: {t['usage']}" if t["usage"] else f"`{t['name']}`.", "  ")
        out.append(f"  final List<BoxShadow> {t['field']};")
    out += [
        "",
        "  /// Interpolates every shadow list, e.g. while the theme animates.",
        "  static CbTokenShadows lerp(CbTokenShadows a, CbTokenShadows b, double t) {",
        "    return CbTokenShadows(",
    ]
    out += [f"      {t['field']}: BoxShadow.lerpList(a.{t['field']}, b.{t['field']}, t)!," for t in tokens]
    out += ["    );", "  }"]
    for theme in themes:
        out += ["", f"  /// Theme `{theme}`.", f"  static const {camel(theme)} = CbTokenShadows("]
        for t in tokens:
            layers = t["values"][theme]
            one_line = f"    {t['field']}: [{', '.join(box_shadow(s) for s in layers)}],"
            if len(one_line) <= 80:
                out.append(one_line)
            else:
                out.append(f"    {t['field']}: [")
                for s in layers:
                    item = f"      {box_shadow(s)},"
                    if len(item) <= 80:
                        out.append(item)
                    else:
                        inner = box_shadow(s)[len("BoxShadow("):-1].split(", ")
                        out.append("      BoxShadow(")
                        out += [f"        {arg}," for arg in inner]
                        out.append("      ),")
                out.append("    ],")
        out.append("  );")
    out.append("}")
    return out


# --------------------------------------------------------------------------- #
# Numeric scales
# --------------------------------------------------------------------------- #


def gen_scale(section: dict, section_name: str, class_name: str, intro: list[str], field_of) -> list[str]:
    out = list(intro)
    note = section.get("note")
    if note:
        out += ["///"] + doc(note, "")
    out.append(f"abstract final class {class_name} {{")
    seen = set()
    for i, token in enumerate(require(section, "tokens", section_name)):
        name = require(token, "name", f"{section_name}.tokens[]")
        field = field_of(name)
        if field in seen:
            raise TokenError(f"{section_name}: duplicate field {field!r}")
        seen.add(field)
        if i:
            out.append("")
        out += doc(f"`{name}`: {token['usage']}" if token.get("usage") else f"`{name}`.", "  ")
        out.append(f"  static const double {field} = {num(px(token['value'], name))};")
    out.append("}")
    return out


def space_field(name: str) -> str:
    suffix = strip_prefix(name, "space-")
    if not suffix.isdigit():
        raise TokenError(f"spacing token {name!r} should be space-<number>")
    return f"s{suffix}"


def radius_field(name: str) -> str:
    return camel(strip_prefix(name, "radius-"))


# --------------------------------------------------------------------------- #
# Typography
# --------------------------------------------------------------------------- #


def first_family(stack: str) -> str:
    first = stack.split(",")[0].strip()
    return first.strip("\"'")


def gen_type(type_section: dict) -> list[str]:
    families = require(type_section, "families", "type")
    out = [
        "/// Font families (`type.families`). [familyName] is the first family of the",
        "/// CSS stack; the theme loads it through Google Fonts.",
        "enum CbFontFamily {",
    ]
    keys = list(families.keys())
    for i, key in enumerate(keys):
        out += doc(f"CSS: {families[key]}", "  ")
        terminator = ";" if i == len(keys) - 1 else ","
        out.append(f"  {camel(key)}({dart_string(first_family(families[key]))}){terminator}")
        out.append("")
    out += [
        "  const CbFontFamily(this.familyName);",
        "",
        "  /// The font family name, e.g. `Helvetica Neue`.",
        "  final String familyName;",
        "}",
        "",
        "/// One text style from `type.groups[].styles[]`, before a font is applied.",
        "class CbTypeSpec {",
        "  const CbTypeSpec({",
        "    required this.name,",
        "    required this.family,",
        "    required this.fontSize,",
        "    required this.height,",
        "    required this.fontWeight,",
        "    this.letterSpacing = 0,",
        "  });",
        "",
        "  /// Token name, e.g. `display-xl`.",
        "  final String name;",
        "",
        "  /// Font family key of the style's group.",
        "  final CbFontFamily family;",
        "",
        "  /// Font size in logical pixels.",
        "  final double fontSize;",
        "",
        "  /// Line height as a multiple of [fontSize] (lineHeight / fontSize).",
        "  final double height;",
        "",
        "  /// Font weight.",
        "  final FontWeight fontWeight;",
        "",
        "  /// Letter spacing in logical pixels (em x fontSize).",
        "  final double letterSpacing;",
        "",
        "  /// Line height in logical pixels.",
        "  double get lineHeight => fontSize * height;",
        "}",
        "",
        "/// The type scale (`type.groups`).",
        "abstract final class CbTypeScale {",
    ]
    names = []
    first = True
    for group in require(type_section, "groups", "type"):
        family_key = require(group, "family", "type.groups[]")
        if family_key not in families:
            raise TokenError(f"type group {group.get('name')!r} uses unknown family {family_key!r}")
        for style in require(group, "styles", f"type group {group.get('name')}"):
            name = require(style, "name", "type style")
            field = camel(name)
            names.append(field)
            size = px(require(style, "fontSize", name), f"{name}.fontSize")
            line = px(require(style, "lineHeight", name), f"{name}.lineHeight")
            weight = int(require(style, "fontWeight", name))
            if weight % 100 or not 100 <= weight <= 900:
                raise TokenError(f"{name}: fontWeight must be 100..900 in steps of 100, got {weight}")
            if not first:
                out.append("")
            first = False
            text = f"`{name}` ({group.get('name', family_key)}): {style.get('usage', '')}".strip()
            if style.get("sample"):
                text += f" Sample: {style['sample']}"
            out += doc(text, "  ")
            out += [
                f"  static const {field} = CbTypeSpec(",
                f"    name: {dart_string(name)},",
                f"    family: CbFontFamily.{camel(family_key)},",
                f"    fontSize: {num(size)},",
                f"    height: {num(line)} / {num(size)},",
                f"    fontWeight: FontWeight.w{weight},",
            ]
            if style.get("letterSpacing") not in (None, ""):
                spacing = em(style["letterSpacing"], f"{name}.letterSpacing")
                out.append(f"    letterSpacing: {num(spacing * size)}, // {style['letterSpacing']}")
            out.append("  );")
    out += ["", "  /// Every style, in token order.", "  static const all = <CbTypeSpec>["]
    out += [f"    {n}," for n in names]
    out += ["  ];", "}"]
    return out


# --------------------------------------------------------------------------- #
# Entry point
# --------------------------------------------------------------------------- #


def generate(tokens: dict) -> str:
    themes, colors = resolve_colors(require(tokens, "color", "tokens.json"))
    sections = [
        gen_colors(themes, colors),
        gen_shadows(themes, require(tokens, "shadow", "tokens.json")),
        gen_scale(require(tokens, "spacing", "tokens.json"), "spacing", "CbSpace",
                  ["/// Spacing scale (`spacing.tokens`), in logical pixels."], space_field),
        gen_scale(require(tokens, "radius", "tokens.json"), "radius", "CbRadius",
                  ["/// Corner radii (`radius.tokens`), in logical pixels."], radius_field),
        gen_scale(require(tokens, "size", "tokens.json"), "size", "CbSize",
                  ["/// Component sizes (`size.tokens`), in logical pixels."], camel),
        gen_type(require(tokens, "type", "tokens.json")),
    ]
    lines = [
        HEADER,
        f"// Design system: {tokens.get('name', '?')}, tokens version {tokens.get('version', '?')}.",
        "// Regenerate: python3 tools/gen_flutter_tokens.py",
        "",
        "import 'package:flutter/painting.dart';",
    ]
    for section in sections:
        lines.append("")
        lines += section
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="do not write; exit 1 if the generated file is out of date")
    args = parser.parse_args()
    try:
        tokens = json.loads(SOURCE.read_text(encoding="utf-8"))
        output = generate(tokens)
    except (OSError, json.JSONDecodeError, TokenError) as error:
        print(f"gen_flutter_tokens: {error}", file=sys.stderr)
        return 2
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
    if args.check:
        if current != output:
            print(f"{TARGET.relative_to(ROOT)} is out of date: run python3 tools/gen_flutter_tokens.py",
                  file=sys.stderr)
            return 1
        print(f"{TARGET.relative_to(ROOT)} is up to date")
        return 0
    if current == output:
        print(f"{TARGET.relative_to(ROOT)} is up to date")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(output, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
