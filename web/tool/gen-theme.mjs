#!/usr/bin/env node
// Generates src/styles/theme.css from src/styles/tokens.css: the design tokens' light and dark colours and shadows
// again, each set under data-theme on <html>, for a theme picked in Settings over the system's (src/theme.ts).
// tokens.css has the light ones on :root and the dark ones under prefers-color-scheme: dark, which only the system
// switches.
//
//   node tool/gen-theme.mjs            writes src/styles/theme.css (npm run tokens does it after tokens.css)
//   node tool/gen-theme.mjs --check    exits 1 if src/styles/theme.css is stale (npm run check-tokens, in CI)
//
// Node standard library only: CI checks the tokens before npm ci.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const styles = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'styles');
const SOURCE = join(styles, 'tokens.css');
const TARGET = join(styles, 'theme.css');
const check = process.argv.includes('--check');

const tokens = readFileSync(SOURCE, 'utf8');

/** The `--name: value;` declarations of a block, in their order. */
function declarations(block) {
  return [...block.matchAll(/^\s*(--[a-z0-9-]+):\s*(.+);$/gm)].map(([, name, value]) => [name, value]);
}

const lightStart = tokens.indexOf(':root {');
const darkStart = tokens.indexOf('@media (prefers-color-scheme: dark)');
if (lightStart < 0 || darkStart < lightStart) throw new Error(`${SOURCE}: no :root block followed by the dark one`);
const light = new Map(declarations(tokens.slice(lightStart, darkStart)));
// What the dark theme changes: the colours (aliases such as --success follow by themselves) and the shadows.
const dark = declarations(tokens.slice(darkStart));
if (dark.length === 0) throw new Error(`${SOURCE}: the dark block has no tokens`);

function block(theme, values) {
  return [
    `:root[data-theme="${theme}"] {`,
    `  color-scheme: ${theme};`,
    ...values.map(([n, v]) => `  ${n}: ${v};`),
    '}',
  ];
}

const css = [
  '/* GENERATED by tool/gen-theme.mjs from tokens.css — do not edit. Regenerate: npm run tokens (in web/).',
  "   A theme picked in Settings (data-theme on <html>: src/theme.ts, index.html) over the system's. */",
  '',
  ...block(
    'light',
    dark.map(([name]) => {
      if (!light.has(name)) throw new Error(`${SOURCE}: ${name} has a dark value but no light one`);
      return [name, light.get(name)];
    }),
  ),
  '',
  ...block('dark', dark),
  '',
].join('\n');

if (check) {
  if (!existsSync(TARGET) || readFileSync(TARGET, 'utf8') !== css) {
    console.error('src/styles/theme.css is stale: run npm run tokens (in web/).');
    process.exit(1);
  }
  console.log('src/styles/theme.css is current.');
} else {
  writeFileSync(TARGET, css);
  console.log('Wrote src/styles/theme.css.');
}
