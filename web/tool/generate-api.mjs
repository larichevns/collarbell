#!/usr/bin/env node
// Writes the API's TypeScript types, src/api/schema.d.ts, from the contract the server publishes,
// contracts/openapi.json (the same source as the phone app's Dart client), with openapi-typescript.
//
//   npm run generate-api              writes src/api/schema.d.ts
//   npm run generate-api -- --check   exits 1 if src/api/schema.d.ts is stale (CI)
//
// The output is committed, so building the app needs only web/.
//
// openapi-typescript builds the types with the TypeScript compiler's JavaScript API. TypeScript 7, which type-checks
// this app, is a native program without that API, so openapi-typescript gets TypeScript 6 instead: the same compiler
// as a JavaScript library, published as @typescript/typescript6. The hook below hands it over when openapi-typescript
// imports "typescript" (and package.json's "overrides" tells npm that openapi-typescript's "typescript ^5" peer is
// taken care of).

import { readFileSync, writeFileSync } from 'node:fs';
import { registerHooks } from 'node:module';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

registerHooks({
  resolve: (specifier, context, nextResolve) =>
    nextResolve(specifier === 'typescript' ? '@typescript/typescript6' : specifier, context),
});

const { default: openapiTS, astToString } = await import('openapi-typescript');

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = join(here, '..', '..', 'contracts', 'openapi.json');
const TARGET = join(here, '..', 'src', 'api', 'schema.d.ts');
const SHOWN = relative(process.cwd(), TARGET);

const types = astToString(await openapiTS(pathToFileURL(SOURCE)));
const file = `/* GENERATED by tool/generate-api.mjs from contracts/openapi.json — do not edit.
   Regenerate: npm run generate-api (in web/). */

${types}`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(TARGET, 'utf8');
  } catch {
    // Missing counts as stale.
  }
  if (current !== file) {
    console.error(`${SHOWN} is stale: run npm run generate-api`);
    process.exit(1);
  }
  console.log(`${SHOWN} is up to date`);
} else {
  writeFileSync(TARGET, file);
  console.log(`Wrote ${SHOWN}`);
}
